def config_dict(encoding, csv=None, servers=SERVERS, tau=TAU_MASTIC):
    """Driver config for one encoding: the benchmark's base settings with Melbourne's encoding,
    tau, 24 hour-of-day buckets and the smaller upload batch. `csv` defaults to the app set as a
    path relative to the repo (the driver runs from the repo root)."""
    spec = ENCODINGS[encoding]
    csv = csv if csv is not None else report_path("snapshot").relative_to(REPO).as_posix()
    return {
        "mode": {"weighted_heavy_hitters": {"threshold": tau}},
        "data_bits": spec["data_bits"],
        **bc.BASE_CONFIG,
        "hist_buckets": HIST_BUCKETS,
        "add_report_share_batch_size": UPLOAD_BATCH,
        "server_0": servers[0],
        "server_1": servers[1],
        "dataset": {"path": str(csv), "encoding": {encoding: dict(spec["params"])},
                    "weight": {"hour_of_day": {"buckets": HIST_BUCKETS}}},
    }


def config_text(cfg, header=None):
    """TOML for a config_dict, in the layout of src/configs (bench/scripts/run_bench.py's value
    writer); checked to read back as `cfg`."""
    import tomllib

    import run_bench

    v = run_bench.toml_value
    lines = [header] if header else []
    lines.append(f"mode.weighted_heavy_hitters.threshold = {v(cfg['mode']['weighted_heavy_hitters']['threshold'])}")
    lines += [f"{k} = {v(x)}" for k, x in cfg.items() if k not in ("mode", "dataset")]
    lines += ["", "[dataset]"]
    for k, x in cfg["dataset"].items():
        if isinstance(x, dict) and len(x) == 1:  # encoding.morton = {...}, weight.hour_of_day = {...}
            (variant, body), = x.items()
            lines.append(f"{k}.{variant} = {v(body)}")
        else:
            lines.append(f"{k} = {v(x)}")
    text = "\n".join(lines) + "\n"
    if tomllib.loads(text) != cfg:
        raise ValueError(f"config for {cfg['dataset']['encoding']} does not read back as intended")
    return text


def write_config(path, cfg, header=None):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(config_text(cfg, header), encoding="utf-8", newline="\n")


def committed_config_text(encoding):
    header = CONFIG_HEADER.format(tau=TAU_MASTIC, buckets=HIST_BUCKETS)
    return config_text(config_dict(encoding), header)


def write_configs():
    for name in ENCODINGS:
        path = config_path(name)
        path.write_text(committed_config_text(name), encoding="utf-8", newline="\n")
        print(f"wrote {relpath(path)}")


def check_configs():
    """True if every src/configs/parking-day-*.toml equals what write_configs would write."""
    ok = True
    for name in ENCODINGS:
        path = config_path(name)
        want = committed_config_text(name)
        got = path.read_text(encoding="utf-8") if path.exists() else None
        status = "equal" if got == want else ("missing" if got is None else "DIFFERS")
        ok &= got == want
        print(f"  {relpath(path)}: {status}")
    return ok

